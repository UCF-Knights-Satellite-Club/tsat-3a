"""Using the PCB stator as a magnetorquer.

Run from sim/:  .venv/bin/python -m pcbmotor.magnetorquer
Writes results/pcbmotor_magnetorquer.json and results/pcbmotor_magnetorquer.md.

Every coil in these concentrated windings points the same way (phase_map gives each phase the same
sign count), and in a star winding the three phase currents sum to zero. Normal motor drive therefore
makes no net magnetic dipole. Bringing out the star point (neutral) and driving a common-mode
(zero-sequence) current I0 through all three phases (a fourth inverter leg) gives a dipole along the
wheel axis:

    m = I0 * sum over coils of (sign * turns * enclosed area)

The common-mode current sees the three phases in parallel (R_phase / 3). Its torque on the rotor is
I0 * (k_a + k_b + k_c)(theta): zero on average for a balanced winding, but the triplen harmonics of
the back-EMF leave a ripple at three times the electrical frequency. The encoder knows theta, so the
FOC loop can cancel it; it is reported so the driver can be sized for it.

Figure of merit: m^2 / P [(A·m²)²/W]. For comparison, a dedicated air-core coil around the edge of a
90 mm board (80 turns of 0.3 mm, 1 oz copper; an ASSUMED example design) is computed the same way.
Earth-field torque is m * B with B = 30 µT (LEO order of magnitude).
"""
from __future__ import annotations

import json
import math
import pathlib

import numpy as np

from .geometry import StatorDesign, RotorDesign, coil_turns, phase_map
from .em import phase_resistance, coil_torque_curve, foc_torque, RHO_CU_20C

OUT = pathlib.Path(__file__).resolve().parents[1] / "results"
B_EARTH_T = 30e-6
DESIGNS = ("test", "payload", "payload_high_momentum")


def _area_m2(poly_mm):
    x, y = poly_mm[:, 0], poly_mm[:, 1]
    return 0.5 * abs(np.dot(x, np.roll(y, -1)) - np.dot(y, np.roll(x, -1))) * 1e-6


def dipole_per_amp(d: StatorDesign, n_poles: int):
    """Axial dipole (A·m²) per amp of common-mode current, and per amp in one coil."""
    na_coil = sum(_area_m2(p) for p in coil_turns(d)) * d.layers
    signs = sum(s for _, s in phase_map(d, n_poles))
    # series coils in a phase all carry I0; parallel coils would split it
    per_amp = na_coil * signs if d.series else na_coil * signs / (d.n_coils // 3)
    return per_amp, na_coil


def analyse(d: StatorDesign, r: RotorDesign):
    m_per_A, na_coil = dipole_per_amp(d, r.n_poles)
    R0 = phase_resistance(d) / 3
    fom = m_per_A ** 2 / R0 if m_per_A else 0.0
    th, tq = coil_torque_curve(d, r, n_theta=72)
    kt, _, _, kph = foc_torque(d, r, th, tq)
    zs = kph.sum(axis=0)
    out = dict(dipole_A_m2_per_A=m_per_A, NA_per_coil_m2=na_coil, R_common_mode_ohm=R0,
               fom_Am2sq_per_W=fom, Kt_mNm_per_A=kt * 1e3,
               ripple_peak_mNm_per_A=float(np.abs(zs).max()) * 1e3, ripple_mean_mNm_per_A=float(zs.mean()) * 1e3)
    for m in (0.005, 0.01, 0.05):
        i0 = m / m_per_A if m_per_A else float("inf")
        out[f"I0_A_for_{m:g}"] = i0
        out[f"P_W_for_{m:g}"] = i0 ** 2 * R0
        out[f"ripple_mNm_for_{m:g}"] = out["ripple_peak_mNm_per_A"] * i0
        out[f"earth_torque_uNm_for_{m:g}"] = m * B_EARTH_T * 1e6
    return out


def reference_edge_coil(side_m=0.090, turns=80, trace_m=0.3e-3, oz=1.0):
    a = (side_m - 0.02) ** 2
    length = turns * 4 * (side_m - 0.02)
    R = RHO_CU_20C * length / (trace_m * oz * 34.79e-6)
    return dict(NA_m2=turns * a, R_ohm=R, fom_Am2sq_per_W=(turns * a) ** 2 / R)


def main():
    j = json.loads((OUT / "pcbmotor_designs.json").read_text())
    rows = {}
    for key in DESIGNS:
        d, r = StatorDesign(**j[key]["stator"]), RotorDesign(**j[key]["rotor"])
        rows[key] = analyse(d, r)
    ref = reference_edge_coil()
    (OUT / "pcbmotor_magnetorquer.json").write_text(json.dumps(dict(designs=rows, edge_coil=ref), indent=2))
    md = ["# Stator as a magnetorquer\n",
          "Generated by `pcbmotor/magnetorquer.py`. Common-mode current through all three phases via a neutral "
          "wire; normal three-phase drive makes no net dipole. Earth field 30 µT.\n",
          "| Design | Dipole A·m² per A | Common-mode R Ω | m²/P (A·m²)²/W | Power for 0.01 A·m² | Power for 0.05 A·m² | "
          "Torque ripple on wheel at 0.01 A·m² (mN·m, zero mean) |",
          "|---|---|---|---|---|---|---|"]
    for k, v in rows.items():
        md.append(f"| {k} | {v['dipole_A_m2_per_A']:.3f} | {v['R_common_mode_ohm']:.2f} | {v['fom_Am2sq_per_W']:.4f} | "
                  f"{v['P_W_for_0.01'] * 1e3:.0f} mW | {v['P_W_for_0.05']:.2f} W | ±{v['ripple_mNm_for_0.01']:.2f} |")
    md.append(f"\nReference dedicated edge coil on a 90 mm board (80 turns, 0.3 mm, 1 oz; assumed): "
              f"N·A {ref['NA_m2']:.3f} m², R {ref['R_ohm']:.1f} Ω, m²/P {ref['fom_Am2sq_per_W']:.4f}.")
    md.append(f"\nEarth-field torque: 0.01 A·m² gives {0.01 * B_EARTH_T * 1e6:.1f} µN·m, 0.05 A·m² gives "
              f"{0.05 * B_EARTH_T * 1e6:.1f} µN·m.")
    (OUT / "pcbmotor_magnetorquer.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
